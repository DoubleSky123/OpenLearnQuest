"""
Build the study's test bank (pre / post / delayed): app/data/study/quiz_items.json.

    cd backend
    d:/openLearnquest/venv/Scripts/python.exe build_quiz_bank.py            # write the bank
    d:/openLearnquest/venv/Scripts/python.exe build_quiz_bank.py --check    # is the shipped bank current and valid?
    d:/openLearnquest/venv/Scripts/python.exe build_quiz_bank.py --sheet ../docs/quiz-review.xlsx

Every item is "which program does this correctly?": the template plus the
canonical mutants of 1-3 misconceptions (services/quiz_bank.py). Free: no model
calls, no database. Rebuild after editing TEMPLATES or the misconception
catalog; tests/test_quiz_bank.py fails until you do. Rebuilding changes items
students may already have answered: do not rebuild in the middle of a study
(item ids stay, content may not).
"""
import argparse
import json
import sys
from collections import Counter
from datetime import datetime, timezone

from app.services import misconceptions as mc
from app.services import quiz_bank as qb


def write(items: list[dict]) -> None:
    qb.BANK_PATH.parent.mkdir(parents=True, exist_ok=True)
    doc = {"built": datetime.now(timezone.utc).isoformat(timespec="seconds"),
           "note": "Generated by build_quiz_bank.py from TEMPLATES + the misconception catalog. Do not edit by hand.",
           "items": items}
    qb.BANK_PATH.write_text(json.dumps(doc, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")


def summary(items: list[dict]) -> None:
    for form in qb.FORMS:
        f = [it for it in items if it["form"] == form]
        n_opts = Counter(len(it["options"]) for it in f)
        pairs = {(it["operation"], o["misconception"]) for it in f for o in it["options"] if o["misconception"]}
        print(f"form {form}: {len(f)} items  options per item {dict(sorted(n_opts.items()))}  "
              f"(operation, misconception) pairs {len(pairs)}")
    by_unit = Counter(it["unit"] for it in items if it["form"] == "A")
    print("items per unit (form A):", dict(by_unit))


def sheet(items: list[dict], path: str) -> None:
    """One row per item: the board, every option with what it is. For the
    teacher to approve or flag before the study."""
    from openpyxl import Workbook
    from openpyxl.styles import Alignment, Font, PatternFill
    wb = Workbook()
    ws = wb.active
    ws.title = "Items"
    head = ["Item", "Form", "Unit", "Operation", "Task", "Board", "Option", "Program (shown to the student)",
            "Right?", "Misconception it shows", "What a student holding it believes", "OK? (yes / no)", "Note"]
    ws.append(head)
    for c in ws[1]:
        c.font = Font(name="Arial", bold=True)
        c.fill = PatternFill("solid", fgColor="DDEBF7")
    for it in items:
        for k, o in enumerate(it["options"]):
            m = mc.CATALOG.get(o["misconception"]) if o["misconception"] else None
            ws.append([it["id"] if k == 0 else "", it["form"] if k == 0 else "", it["unit"] if k == 0 else "",
                       it["operation"] if k == 0 else "", it["prompt"] if k == 0 else "",
                       "\n".join(it["setup"]) if k == 0 else "", chr(ord("a") + k),
                       "\n".join(o["lines"]), "RIGHT" if o["correct"] else "", o["misconception"] or "",
                       m.belief if m else "", "", ""])
    widths = [20, 6, 12, 18, 40, 34, 7, 70, 8, 22, 50, 12, 30]
    for i, w in enumerate(widths):
        ws.column_dimensions[chr(ord("A") + i)].width = w
    for row in ws.iter_rows(min_row=2):
        for c in row:
            c.font = Font(name="Courier New" if c.column == 8 else "Arial")
            c.alignment = Alignment(wrap_text=True, vertical="top")
    ws.freeze_panes = "A2"
    guide = wb.create_sheet("Start here", 0)
    for line in [
        "Study test items: please review",
        "",
        "Every item asks: which program does this correctly? One option is the correct program; each other "
        "option is what a student holding one misconception writes.",
        "The program was run on the board shown: the right option works there and every other option fails there.",
        "Forms A and B test the same misconceptions on different lists (pre-test on one form, post-test on the other).",
        "",
        "Please fill in column L (yes / no) for each option row, and column M if something reads badly or the "
        "misconception label does not fit.",
        "Example: a row with 'no' and the note 'option c is unreadable, too long' is enough.",
    ]:
        guide.append([line])
    guide.column_dimensions["A"].width = 120
    for row in guide.iter_rows():
        for c in row:
            c.font = Font(name="Arial", bold=c.row == 1)
            c.alignment = Alignment(wrap_text=True)
    wb.save(path)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="verify the shipped bank; write nothing")
    ap.add_argument("--sheet", help="also write a teacher review sheet (.xlsx)")
    args = ap.parse_args()

    fresh = qb.build()
    problems = {it["id"]: qb.verify(it) for it in fresh}
    problems = {k: v for k, v in problems.items() if v}
    for k, v in problems.items():
        print(f"  {k}: {'; '.join(v)}")
    if args.check:
        shipped = list(qb.load())
        if not shipped:
            print("no bank at", qb.BANK_PATH)
            return 1
        stale = [it["id"] for it in shipped if qb.verify(it)]
        changed = {it["id"] for it in shipped} != {it["id"] for it in fresh} or \
            [{k: v for k, v in it.items()} for it in shipped] != fresh
        print(f"shipped bank: {len(shipped)} items, {len(stale)} failing checks, "
              f"{'differs from' if changed else 'matches'} a fresh build")
        return 1 if stale or problems else 0
    if problems:
        print("not written: fix the items above")
        return 1
    write(fresh)
    summary(fresh)
    print("wrote", qb.BANK_PATH)
    if args.sheet:
        sheet(fresh, args.sheet)
        print("wrote", args.sheet)
    return 0


if __name__ == "__main__":
    sys.exit(main())
